def simulate_multi_asset(S0, mu, sigma, corr_matrix, T, N):
    import numpy as np

    num_assets = len(S0)
    dt = T / N

    L = np.linalg.cholesky(corr_matrix)


    Z = np.random.normal(0, 1, (num_assets, N))

    correlated_Z = L @ Z

    dW = np.sqrt(dt) * correlated_Z
    W = np.cumsum(dW, axis=1)
    W = np.hstack([np.zeros((num_assets, 1)), W])

    t = np.linspace(0, T, N+1)

    S = np.zeros((num_assets, N+1))

    for i in range(num_assets):
        S[i] = S0[i] * np.exp(
            (mu[i] - 0.5 * sigma[i]**2) * t + sigma[i] * W[i]
        )

    return t, S

